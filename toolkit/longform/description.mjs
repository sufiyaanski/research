// description.mjs — YouTube description.md for a long-form episode: hook line + summary, chapter
// timestamps, sources (every URL in facts.md), credits/disclosure, ≤ 3 hashtags. Never uploads anything.
//   node longform/description.mjs <episodeDir>       (render-chapters.mjs calls it after the mix)
import { existsSync, readFileSync, writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { youtubeChapters } from './plan.mjs';

export function writeDescription(epDir, ep, timeline, chaptersText) {
  const facts = existsSync(path.join(epDir, 'facts.md')) ? readFileSync(path.join(epDir, 'facts.md'), 'utf8') : '';
  // a source = a markdown link or bare URL in facts.md, with the text before it on that line as the label
  const sources = [];
  for (const line of facts.split('\n')) {
    for (const m of line.matchAll(/\[([^\]]+)\]\((https?:[^)\s]+)\)|(https?:\/\/[^\s)>\]]+)/g)) {
      const url = m[2] ?? m[3];
      const label = m[1] ?? line.replace(url, '').replace(/^[-*\d.\s|]+/, '').split('|')[0].trim().slice(0, 90);
      if (!sources.some((s) => s.url === url)) sources.push({ label, url });
    }
  }
  const voice = timeline.voice;
  const tags = (ep.hashtags ?? []).slice(0, 3).map((h) => (h.startsWith('#') ? h : `#${h}`));
  const md = [
    `<!-- generated by longform/description.mjs — edit episode.json / facts.md and re-run, or edit here before upload -->`,
    `# ${ep.title}`,
    '',
    ep.hook ?? '',
    '',
    ep.summary ?? '',
    '',
    '## Chapters',
    chaptersText,
    '',
    '## Sources',
    ...(sources.length ? sources.map((s) => `- ${s.label ? `${s.label}: ` : ''}${s.url}`) : ['- (none listed — facts.md is empty; do not publish numbers without sources)']),
    '',
    '## Credits',
    `- Animation: made in code (Remotion), original characters and sets.`,
    `- Narration: ${voice.mock ? 'MOCK (silent placeholder — not publishable)' : voice.source.startsWith('elevenlabs') ? 'synthetic voice (ElevenLabs)' : `synthetic voice (${voice.source.split(':')[0]}, open model)`}.`,
    `- Music and sound effects: synthesised in code for this channel.`,
    `- Speculative scenario: the "what if" events are hypothetical; the science behind each step is sourced above.`,
    '',
    tags.join(' '),
    '',
  ].join('\n');
  const f = path.join(epDir, 'description.md');
  writeFileSync(f, md);
  return f;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const dir = path.resolve(process.argv[2] ?? '.');
  const ep = JSON.parse(readFileSync(path.join(dir, 'episode.json'), 'utf8'));
  const timeline = JSON.parse(readFileSync(path.join(dir, 'timeline.json'), 'utf8'));
  console.log(writeDescription(dir, ep, timeline, youtubeChapters(timeline).text));
}
