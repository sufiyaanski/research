#!/usr/bin/env node
// Generate vo.gen.ts (word-level timings) from an episode's beats.json.
//
//   node remotion/scripts/estimate-vo.mjs signal-001-anchoring
//
// PLACEHOLDER MODE (default): distributes each VO line's [start,end] window over its words,
// weighted by word length. Good enough to build and QA a composition before the voice exists.
//
// REAL MODE: when a TTS/alignment tool has written `words: [{w,start,end}]` on each vo line
// in beats.json (ElevenLabs /with-timestamps, WhisperX, etc.), those are copied verbatim.
// Captions then highlight on the exact spoken word. Never hand-edit vo.gen.ts.
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const id = process.argv[2];
if (!id) {
  console.error('usage: node remotion/scripts/estimate-vo.mjs <episode-id>   e.g. signal-001-anchoring');
  process.exit(1);
}
const dir = path.join(root, 'remotion', 'src', 'episodes', id);
const beatsPath = path.join(dir, 'beats.json');
if (!existsSync(beatsPath)) {
  console.error(`no beats.json at ${beatsPath}`);
  process.exit(1);
}
const beats = JSON.parse(readFileSync(beatsPath, 'utf8'));

const estimate = (line) => {
  const words = line.text.split(/\s+/).filter(Boolean);
  const weights = words.map((w) => Math.max(2, w.replace(/[^a-zA-Z0-9]/g, '').length) + 1.6);
  const total = weights.reduce((a, b) => a + b, 0);
  const span = line.end - line.start;
  let t = line.start;
  return words.map((w, i) => {
    const d = (weights[i] / total) * span;
    const out = { w, start: +t.toFixed(3), end: +(t + d).toFixed(3) };
    t += d;
    return out;
  });
};

let real = 0;
const lines = beats.vo.map((line) => {
  const words = Array.isArray(line.words) && line.words.length ? (real++, line.words) : estimate(line);
  return { beat: line.beat, text: line.text, start: line.start, end: line.end, words };
});

// sanity: lines must not overlap, and must speak at a humane rate
let prevEnd = -1;
for (const l of lines) {
  if (l.start < prevEnd) console.warn(`WARN: line "${l.text}" starts (${l.start}) before previous ends (${prevEnd})`);
  const wps = l.words.length / Math.max(0.1, l.end - l.start);
  if (wps > 3.2) console.warn(`WARN: ${wps.toFixed(2)} words/s in "${l.text}" — TTS will need to squeeze; widen the window or cut words`);
  prevEnd = l.end;
}

const mode = real === lines.length ? 'REAL word alignment copied from beats.json' : real > 0 ? 'MIXED (some lines estimated)' : 'ESTIMATED timings (placeholder — regenerate after TTS)';
const body = lines
  .map((l) => {
    const ws = l.words.map((w) => `{ w: ${JSON.stringify(w.w)}, start: ${w.start}, end: ${w.end} }`).join(', ');
    return `  { beat: ${JSON.stringify(l.beat)}, text: ${JSON.stringify(l.text)}, start: ${l.start}, end: ${l.end}, words: [${ws}] },`;
  })
  .join('\n');

const out = `// AUTO-GENERATED by remotion/scripts/estimate-vo.mjs from beats.json — do not edit by hand.
// Mode: ${mode}
import type { VoLine } from '../../lib/kit';

export const VO: VoLine[] = [
${body}
];
`;
writeFileSync(path.join(dir, 'vo.gen.ts'), out);
console.log(`wrote ${path.relative(root, path.join(dir, 'vo.gen.ts'))} (${lines.length} lines, ${mode})`);
