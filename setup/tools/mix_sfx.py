#!/usr/bin/env python3
"""
mix_sfx.py — lay the episode's SFX cues on the global timeline and mux them (plus the voice) onto the render.

Reads sfx-plan.json (the cue sheet: one event per cue, SECONDS on the same clock as beats.json
and the Remotion composition), resolves each cue id through media/library/sfx/catalog.json,
builds ONE ffmpeg filter_complex (adelay -> volume -> amix), lightly ducks the SFX bus under
the voice, and writes the video with the summed audio. Remotion renders are silent unless the
composition mounts <Audio>; pass --vo episodes/<id>/voice/voice.wav to mix the voice in here.

sfx-plan.json:
  {
    "video": "../../out/SignalAnchoring.mp4",   # relative to the plan's dir, then repo root
    "vo": "voice/voice.wav",                      # optional; CLI --vo overrides
    "fps": 60, "out": "../../out/SignalAnchoring-sfx.mp4",
    "catalog": "media/library/sfx/catalog.json",
    "cues": [
      { "id": "whoosh-soft", "at_s": 3.5,  "gain_db": -3, "note": "cut hook -> setup" },
      { "id": "pop-reveal",  "at_f": 684,  "gain_db": 0,  "optional": false, "note": "$429 tag lands (frame 684)" }
    ]
  }
  at_s / at_f (frames at `fps`) is WHERE THE HIT LANDS: the clip is started `peak_s` (catalog)
  earlier so a whoosh peaks ON the cut. "align": "start" places the file start at at_s instead.

No plan yet? Build one from the composition's beats.json hints (beats[].sfx = ["id@seconds", "id@seconds?"],
'?' = optional):
  python3 -I tools/mix_sfx.py --from-beats remotion/src/episodes/<id>/beats.json --print
  python3 -I tools/mix_sfx.py --from-beats ... --write-plan episodes/<id>/sfx-plan.json   # then edit + audit it

Usage:
  python3 -I tools/mix_sfx.py episodes/<id>/sfx-plan.json --print                 # cue sheet with frames, no render
  python3 -I tools/mix_sfx.py episodes/<id>/sfx-plan.json --vo episodes/<id>/voice/voice.wav
  python3 -I tools/mix_sfx.py <plan> --no-optional --out x.mp4 --bus sfx-bus.wav --no-duck --strict

Missing clips are reported and SKIPPED (the mix still renders) so a half-built library never
blocks a review loop; --strict turns that into exit 1. ffmpeg/ffprobe on PATH.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CATALOG = os.path.join("media", "library", "sfx", "catalog.json")
SR = 48000


def log(msg: str) -> None:
    print(msg, file=sys.stderr)


def run(cmd: list[str]) -> str:
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if r.returncode != 0:
        sys.exit(f"ffmpeg failed ({r.returncode}):\n  {' '.join(cmd)}\n{r.stdout[-3000:]}")
    return r.stdout


def resolve(p: str, bases: list[str]) -> str:
    if os.path.isabs(p):
        return p
    for b in bases:
        c = os.path.normpath(os.path.join(b, p))
        if os.path.exists(c):
            return c
    return os.path.normpath(os.path.join(bases[0], p))


def show(p: str | None) -> str:
    if not p:
        return "-"
    rel = os.path.relpath(p, os.getcwd())
    return p if rel.startswith("..") else rel


def probe(path: str) -> dict:
    j = json.loads(run(["ffprobe", "-v", "error", "-show_entries", "stream=codec_type:format=duration", "-of", "json", path]))
    return {"duration": float(j["format"]["duration"]),
            "has_audio": any(s.get("codec_type") == "audio" for s in j.get("streams", []))}


def plan_from_beats(beats_path: str) -> tuple[dict, str]:
    """Turn beats[].sfx hints ("id@seconds", trailing '?' = optional) into a plan dict."""
    with open(beats_path, encoding="utf-8") as f:
        beats = json.load(f)
    fps = int(beats.get("fps") or beats.get("format", {}).get("fps") or 60)
    comp = beats.get("composition") or beats.get("id") or "Episode"
    ep_id = beats.get("id") or os.path.basename(os.path.dirname(beats_path))
    cues = []
    for b in beats.get("beats", []):
        for hint in b.get("sfx", []) or []:
            if not isinstance(hint, str) or "@" not in hint:
                continue
            sid, at = hint.rsplit("@", 1)
            optional = at.endswith("?")
            at = at.rstrip("?")
            try:
                at_s = float(at)
            except ValueError:
                continue
            if at_s < float(b.get("start", 0)) - 1.5 or at_s > float(b.get("end", 1e9)) + 0.5:
                log(f"  note: {hint} lies outside beat '{b.get('id')}' ({b.get('start')}-{b.get('end')}s) — treated as global seconds anyway")
            cues.append({"id": sid, "at_s": at_s, "gain_db": 0, "optional": optional, "note": f"beat '{b.get('id')}' hint"})
    plan = {"_note": f"generated by mix_sfx.py --from-beats from {os.path.relpath(beats_path, ROOT)} — edit gains/notes, then audit with --print",
            "video": os.path.join(ROOT, "out", f"{comp}.mp4"), "vo": os.path.join(ROOT, "episodes", ep_id, "voice", "voice.wav"),
            "fps": fps, "out": os.path.join(ROOT, "out", f"{comp}-sfx.mp4"), "catalog": DEFAULT_CATALOG, "cues": cues}
    return plan, os.path.dirname(beats_path)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("plan", nargs="?", help="sfx-plan.json")
    ap.add_argument("--from-beats", help="build the cue list from beats[].sfx hints in this beats.json")
    ap.add_argument("--write-plan", help="with --from-beats: save the generated plan here (relative paths)")
    ap.add_argument("--print", dest="print_only", action="store_true", help="show the resolved cue sheet, no render")
    ap.add_argument("--fps", type=int, help="override fps for frame numbers")
    ap.add_argument("--video", help="override the plan's video")
    ap.add_argument("--vo", help="voice.wav to mix in when the render is silent (overrides plan 'vo')")
    ap.add_argument("--out", help="override output path")
    ap.add_argument("--bus", help="also write the SFX-only bus as wav")
    ap.add_argument("--no-optional", action="store_true", help='drop cues marked "optional": true')
    ap.add_argument("--no-duck", action="store_true", help="do not duck SFX under the voice")
    ap.add_argument("--ref-lufs", type=float, default=None,
                    help="compensate clips whose catalog loudness_lufs is below this (default: catalog _schema.ref_lufs)")
    ap.add_argument("--strict", action="store_true", help="exit 1 if any cue is missing")
    args = ap.parse_args()

    if args.from_beats:
        plan, plan_dir = plan_from_beats(os.path.abspath(args.from_beats))
        plan_path = os.path.join(plan_dir, "sfx-plan.generated.json")
        if args.write_plan:
            wp = os.path.abspath(args.write_plan)
            os.makedirs(os.path.dirname(wp), exist_ok=True)
            rel = dict(plan)
            for k in ("video", "vo", "out"):
                rel[k] = os.path.relpath(plan[k], os.path.dirname(wp))
            with open(wp, "w", encoding="utf-8") as f:
                json.dump(rel, f, indent=2, ensure_ascii=False)
                f.write("\n")
            log(f"plan written -> {wp}")
            plan_path, plan_dir = wp, os.path.dirname(wp)
    elif args.plan:
        plan_path = os.path.abspath(args.plan)
        plan_dir = os.path.dirname(plan_path)
        with open(plan_path, encoding="utf-8") as f:
            plan = json.load(f)
    else:
        ap.error("give a sfx-plan.json or --from-beats beats.json")

    # accept the composition-side plan shape too: master/master_fps/events[].sfx/cue/music{}
    if "video" not in plan and plan.get("master"):
        plan["video"] = plan["master"]
    if "fps" not in plan and plan.get("master_fps"):
        plan["fps"] = plan["master_fps"]
    bases = [plan_dir, ROOT, os.getcwd()]
    fps = args.fps or int(plan.get("fps", 60))
    catalog_path = resolve(plan.get("catalog", DEFAULT_CATALOG), [ROOT, plan_dir])
    with open(catalog_path, encoding="utf-8") as f:
        catalog = json.load(f)
    lib = {c["id"]: c for c in catalog.get("clips", [])}
    sfx_root = os.path.dirname(catalog_path)
    ref_lufs = args.ref_lufs if args.ref_lufs is not None else catalog.get("_schema", {}).get("ref_lufs")

    video = resolve(args.video or plan.get("video", ""), bases) if (args.video or plan.get("video")) else None
    vo = resolve(args.vo or plan.get("vo", ""), bases) if (args.vo or plan.get("vo")) else None
    out = args.out or plan.get("out")
    if out:
        out = os.path.abspath(out) if os.path.isabs(out) else os.path.normpath(os.path.join(plan_dir, out))
    elif video:
        out = os.path.splitext(video)[0] + "-sfx.mp4"

    # ---- resolve cues
    rows, missing = [], []
    for c in plan.get("cues") or plan.get("events") or []:
        cid = c.get("id") or c.get("sfx") or c.get("sfx_id")
        if "note" not in c and c.get("cue"):
            c["note"] = c["cue"]
        if args.no_optional and c.get("optional"):
            continue
        if "at_s" in c:
            at = float(c["at_s"])
        elif "at_f" in c:
            at = float(c["at_f"]) / fps
        else:
            missing.append((cid, "no at_s/at_f"))
            continue
        clip = lib.get(cid)
        row = {"id": cid, "at": at, "gain": float(c.get("gain_db", 0)), "comp": 0.0, "optional": bool(c.get("optional")),
               "note": c.get("note", ""), "dur": None, "status": "ok"}
        if not clip:
            row["status"] = "NOT IN CATALOG"
            missing.append((cid, "not in catalog (add to palette.json + gen_sfx.py, or --import)"))
            rows.append(row)
            continue
        path = os.path.join(sfx_root, clip["file"])
        peak = 0.0 if c.get("align") == "start" else float(clip.get("peak_s") or 0.0)
        row.update({"start": max(0.0, at - peak), "file": path, "dur": clip.get("duration_s")})
        if ref_lufs is not None and clip.get("loudness_lufs") is not None:
            row["comp"] = max(0.0, round(float(ref_lufs) - float(clip["loudness_lufs"]), 1))  # lift quiet transients only
        if not os.path.exists(path):
            row["status"] = "FILE MISSING"
            missing.append((cid, f"file missing: {show(path)}"))
        rows.append(row)
    rows.sort(key=lambda r: r["at"])

    # ---- cue sheet
    print(f"plan: {show(plan_path)}   video: {show(video)}   vo: {show(vo)}   fps: {fps}   catalog: {len(lib)} clips")
    print(f"out:  {show(out)}   duck: {not args.no_duck}   ref_lufs: {ref_lufs}")
    print(f"  {'at_s':>7} {'frame':>6}  {'id':<20} {'gain':>5} {'comp':>5} {'dur':>5}  status / note")
    last_at = None
    for r in rows:
        dens = ""
        if last_at is not None and r["at"] - last_at < 0.5 and not r["optional"]:
            dens = "  [<0.5s after previous — intended layer?]"
        last_at = r["at"]
        print(f"  {r['at']:7.3f} {round(r['at']*fps):6d}  {r['id']:<20} {r['gain']:+5.1f} {r['comp']:+5.1f} "
              f"{(r['dur'] or 0):5.2f}  {r['status']}{' (opt)' if r['optional'] else ''} {r['note'][:48]}{dens}")
    hero = [r for r in rows if not r["optional"]]
    vdur = None
    if plan.get("music"):
        m = plan["music"]
        print(f"  music block: bed={m.get('bed')} (mix_music.py handles the bed; --plan reads this)")
    if video and os.path.exists(video):
        vdur = probe(video)["duration"]
        print(f"  density: {len(hero)} required cues over {vdur:.1f}s = 1 per {vdur/max(1,len(hero)):.1f}s (guideline: >= 2 s apart outside layers)")
        late = [r["id"] for r in rows if r["at"] > vdur]
        if late:
            print(f"  WARN {len(late)} cue(s) after video end ({vdur:.2f}s): {', '.join(late)}")
    elif video:
        print(f"  (video not rendered yet: {show(video)})")
    if missing:
        print("  MISSING (skipped): " + "; ".join(f"{i}: {why}" for i, why in missing))
    if args.print_only:
        return
    if args.strict and missing:
        sys.exit(1)

    usable = [r for r in rows if r["status"] == "ok"]
    if not usable:
        sys.exit("no usable cues — nothing to mix")
    if not video or not os.path.exists(video):
        sys.exit(f"video not found: {video}")
    vinfo = probe(video)
    total = vinfo["duration"]
    if vo and not os.path.exists(vo):
        sys.exit(f"voice file not found: {vo}")
    if not vinfo["has_audio"] and not vo:
        log("  WARN: render is silent and no --vo given — output will have SFX only")

    # ---- ffmpeg graph: input 0 = video; input 1 = vo (optional); then one input per clip
    cmd = ["ffmpeg", "-y", "-hide_banner", "-v", "error", "-i", video]
    idx = 1
    dlg_sel = None
    if vo:
        cmd += ["-i", vo]
        dlg_sel = f"{idx}:a"
        idx += 1
    elif vinfo["has_audio"]:
        dlg_sel = "0:a"
    parts, labels = [], []
    for i, r in enumerate(usable):
        cmd += ["-i", r["file"]]
        ms = int(round(r["start"] * 1000))
        parts.append(f"[{idx + i}:a]aformat=sample_rates={SR}:channel_layouts=stereo,adelay={ms}:all=1,"
                     f"volume={r['gain'] + r['comp']:.2f}dB[e{i}]")
        labels.append(f"[e{i}]")
    if len(labels) == 1:
        parts.append(f"{labels[0]}apad,atrim=0:{total:.3f}[bus]")
    else:
        parts.append("".join(labels) + f"amix=inputs={len(labels)}:normalize=0:dropout_transition=0,apad,atrim=0:{total:.3f}[bus]")
    bus_label = "[bus]"
    if args.bus:
        parts.append("[bus]asplit=2[bus_out][bus_mix]")
        bus_label = "[bus_mix]"

    if dlg_sel:
        parts.append(f"[{dlg_sel}]aformat=sample_rates={SR}:channel_layouts=stereo,apad,atrim=0:{total:.3f}[v0]")
        if args.no_duck:
            parts.append(f"[v0]{bus_label}amix=inputs=2:normalize=0:dropout_transition=0[mixraw]")
        else:
            # light duck: tuck SFX ~3-5 dB under loud speech so a cue mid-word never masks a consonant;
            # cues in word gaps pass at full plan gain.
            parts.append("[v0]asplit=2[key][v1]")
            parts.append(f"{bus_label}[key]sidechaincompress=threshold=0.15:ratio=2.5:attack=5:release=180:makeup=1[busduck]")
            parts.append("[v1][busduck]amix=inputs=2:normalize=0:dropout_transition=0[mixraw]")
        parts.append("[mixraw]alimiter=level_in=1:level_out=1:limit=0.95:attack=5:release=50[mix]")
    else:
        parts.append(f"{bus_label}alimiter=level_in=1:level_out=1:limit=0.95[mix]")

    cmd += ["-filter_complex", ";".join(parts), "-map", "0:v:0", "-map", "[mix]",
            "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-ar", str(SR), "-t", f"{total:.3f}", "-movflags", "+faststart", out]
    if args.bus:
        cmd += ["-map", "[bus_out]", "-c:a", "pcm_s16le", "-ar", str(SR), "-t", f"{total:.3f}", args.bus]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    run(cmd)
    log(f"mixed {len(usable)} cues{' + voice' if dlg_sel else ''} -> {out}" + (f"   bus -> {args.bus}" if args.bus else ""))
    if missing:
        log(f"  ({len(missing)} cue(s) skipped — see above)")


if __name__ == "__main__":
    main()
